import fs from "node:fs/promises";
import { Converter } from "opencc-js";

const treeUrl =
  "https://api.github.com/repos/cbeta-org/xml-p5/git/trees/master?recursive=1";
const canonsUrl =
  "https://raw.githubusercontent.com/cbeta-org/xml-p5/master/canons.json";
const rawBase = "https://raw.githubusercontent.com/cbeta-org/xml-p5/master";
const toSimplified = Converter({ from: "tw", to: "cn" });

const responseJson = async (url) => {
  const response = await fetch(url, {
    headers: {
      Accept: "application/vnd.github+json",
      "User-Agent": "sutrareader-catalog-generator",
    },
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status}`);
  }

  return response.json();
};

const responseText = async (url) => {
  const response = await fetch(url, {
    headers: {
      Accept: "application/xml,text/xml,text/plain,*/*",
      "User-Agent": "sutrareader-catalog-generator",
    },
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status}`);
  }

  return response.text();
};

const canonFromPath = (path) => path.split("/")[0];

const volumeFromPath = (path) => {
  const parts = path.split("/");
  return parts.length > 2 ? parts[1] : "";
};

const workNumberFromFile = (fileName) => {
  const match = fileName.match(/n([^.]*)\.xml$/);
  return match?.[1] ?? fileName.replace(/\.xml$/, "");
};

const titleFromPath = (path, canons) => {
  const canon = canonFromPath(path);
  const volume = volumeFromPath(path);
  const fileName = path.split("/").pop() ?? path;
  const sourceId = fileName.replace(/\.xml$/, "");
  const canonTitle = canons[canon]?.["short-title-zh"] ?? canon;
  return `${canonTitle} ${sourceId}`;
};

const decodeXml = (text) =>
  text
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, "\"")
    .replace(/&apos;/g, "'");

const extractHeaderTitle = (xml) => {
  const header = xml.slice(0, Math.min(xml.length, 12000));
  const patterns = [
    /<title\b(?=[^>]*level="m")(?=[^>]*xml:lang="zh-Hant")[^>]*>([\s\S]*?)<\/title>/,
    /<title\b(?=[^>]*level="m")[^>]*>([\s\S]*?)<\/title>/,
    /<title\b(?=[^>]*xml:lang="zh-Hant")[^>]*>([\s\S]*?)<\/title>/,
  ];

  for (const pattern of patterns) {
    const match = header.match(pattern);
    if (match?.[1]) {
      return decodeXml(match[1].replace(/<[^>]+>/g, "").trim());
    }
  }

  return "";
};

const mapConcurrent = async (items, limit, mapper) => {
  const results = new Array(items.length);
  let nextIndex = 0;

  const workers = Array.from({ length: limit }, async () => {
    while (nextIndex < items.length) {
      const index = nextIndex;
      nextIndex += 1;
      results[index] = await mapper(items[index], index);
    }
  });

  await Promise.all(workers);
  return results;
};

const buildSearchText = (item) =>
  toSimplified(
    [
      item.title,
      item.canonTitle,
      item.sourceId,
      item.canon,
      item.volume,
      item.number,
      item.path,
    ].join(" "),
  ).toLowerCase();

const main = async () => {
  const [tree, canons] = await Promise.all([
    responseJson(treeUrl),
    responseJson(canonsUrl),
  ]);

  if (tree.truncated) {
    throw new Error("GitHub returned a truncated CBETA tree");
  }

  const baseWorks = tree.tree
    .filter((entry) => entry.type === "blob" && entry.path.endsWith(".xml"))
    .map((entry) => {
      const canon = canonFromPath(entry.path);
      const volume = volumeFromPath(entry.path);
      const fileName = entry.path.split("/").pop() ?? entry.path;
      const sourceId = fileName.replace(/\.xml$/, "");

      const item = {
        id: sourceId,
        sourceId,
        canon,
        canonTitle: canons[canon]?.["short-title-zh"] ?? canon,
        volume,
        number: workNumberFromFile(fileName),
        title: titleFromPath(entry.path, canons),
        path: entry.path,
        rawUrl: `${rawBase}/${entry.path}`,
      };
      return item;
    })
    .sort((a, b) => a.path.localeCompare(b.path));

  const works = await mapConcurrent(baseWorks, 12, async (item, index) => {
    try {
      const xml = await responseText(item.rawUrl);
      const title = extractHeaderTitle(xml) || item.title;
      const nextItem = {
        ...item,
        title,
      };
      if ((index + 1) % 250 === 0) {
        console.log(`Fetched ${index + 1}/${baseWorks.length} titles`);
      }
      return {
        ...nextItem,
        titleSimplified: toSimplified(nextItem.title),
        canonTitleSimplified: toSimplified(nextItem.canonTitle),
        searchText: buildSearchText(nextItem),
      };
    } catch {
      return {
        ...item,
        titleSimplified: toSimplified(item.title),
        canonTitleSimplified: toSimplified(item.canonTitle),
        searchText: buildSearchText(item),
      };
    }
  });

  const output = `// Generated by scripts/generate-cbeta-catalog.mjs\nimport { CbetaCatalogItem, CbetaCanon } from \"../types\";\n\nexport const cbetaCanons = ${JSON.stringify(
    canons,
    null,
    2,
  )} as Record<string, CbetaCanon>;\n\nexport const cbetaCatalog = ${JSON.stringify(
    works,
    null,
    2,
  )} as CbetaCatalogItem[];\n`;

  await fs.mkdir("src/data", { recursive: true });
  await fs.writeFile("src/data/cbetaCatalog.ts", output);
  console.log(`Wrote ${works.length} CBETA catalog entries`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
