import fs from "node:fs/promises";

const treeUrl =
  "https://api.github.com/repos/cbeta-org/xml-p5/git/trees/master?recursive=1";
const canonsUrl =
  "https://raw.githubusercontent.com/cbeta-org/xml-p5/master/canons.json";
const rawBase = "https://raw.githubusercontent.com/cbeta-org/xml-p5/master";

const responseJson = async (url) => {
  const response = await fetch(url, {
    headers: {
      Accept: "application/vnd.github+json",
      "User-Agent": "sutrareader-catalog-generator",
    },
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status}`);
  }

  return response.json();
};

const canonFromPath = (path) => path.split("/")[0];

const volumeFromPath = (path) => {
  const parts = path.split("/");
  return parts.length > 2 ? parts[1] : "";
};

const workNumberFromFile = (fileName) => {
  const match = fileName.match(/n([^.]*)\.xml$/);
  return match?.[1] ?? fileName.replace(/\.xml$/, "");
};

const titleFromPath = (path, canons) => {
  const canon = canonFromPath(path);
  const volume = volumeFromPath(path);
  const fileName = path.split("/").pop() ?? path;
  const sourceId = fileName.replace(/\.xml$/, "");
  const canonTitle = canons[canon]?.["short-title-zh"] ?? canon;
  return `${canonTitle} ${sourceId}`;
};

const main = async () => {
  const [tree, canons] = await Promise.all([
    responseJson(treeUrl),
    responseJson(canonsUrl),
  ]);

  if (tree.truncated) {
    throw new Error("GitHub returned a truncated CBETA tree");
  }

  const works = tree.tree
    .filter((entry) => entry.type === "blob" && entry.path.endsWith(".xml"))
    .map((entry) => {
      const canon = canonFromPath(entry.path);
      const volume = volumeFromPath(entry.path);
      const fileName = entry.path.split("/").pop() ?? entry.path;
      const sourceId = fileName.replace(/\.xml$/, "");

      return {
        id: sourceId,
        sourceId,
        canon,
        canonTitle: canons[canon]?.["short-title-zh"] ?? canon,
        volume,
        number: workNumberFromFile(fileName),
        title: titleFromPath(entry.path, canons),
        path: entry.path,
        rawUrl: `${rawBase}/${entry.path}`,
      };
    })
    .sort((a, b) => a.path.localeCompare(b.path));

  const output = `// Generated by scripts/generate-cbeta-catalog.mjs\nimport { CbetaCatalogItem, CbetaCanon } from \"../types\";\n\nexport const cbetaCanons = ${JSON.stringify(
    canons,
    null,
    2,
  )} as Record<string, CbetaCanon>;\n\nexport const cbetaCatalog = ${JSON.stringify(
    works,
    null,
    2,
  )} as CbetaCatalogItem[];\n`;

  await fs.mkdir("src/data", { recursive: true });
  await fs.writeFile("src/data/cbetaCatalog.ts", output);
  console.log(`Wrote ${works.length} CBETA catalog entries`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
